#!/usr/bin/env python3
# Make userspace/c-progs/titlefont.h: the compositor's title bar text,
# Inter SemiBold rendered with anti-aliasing (the toolkit's font, so title
# bars match the windows' own text). Each glyph is an 8-bit coverage
# bitmap with its offset from the baseline and its advance in 1/64 pixel.
#
#   scripts/make-title-font.py [SIZE]      (default 14 px; needs Pillow)
import sys, os
from PIL import Image, ImageDraw, ImageFont

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
size = int(sys.argv[1]) if len(sys.argv) > 1 else 14
font = ImageFont.truetype(os.path.join(root, "files/usr/share/fonts/inter/Inter-SemiBold.ttf"), size)
cps = list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) + [
    0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2212, 0x20AC]
ascent, descent = font.getmetrics()
glyphs, data = [], []
for cp in cps:
    ch = chr(cp)
    pad = size
    img = Image.new("L", (size * 3, size * 3), 0)
    ImageDraw.Draw(img).text((pad, pad + ascent), ch, font=font, fill=255, anchor="ls")
    adv = round(font.getlength(ch) * 64)
    box = img.getbbox()
    if box is None:
        glyphs.append((cp, 0, 0, 0, 0, adv, len(data)))
        continue
    x0, y0, x1, y1 = box
    crop = img.crop(box)
    glyphs.append((cp, x0 - pad, y0 - (pad + ascent), x1 - x0, y1 - y0, adv, len(data)))
    data.extend(crop.tobytes())

out = os.path.join(root, "userspace/c-progs/titlefont.h")
with open(out, "w") as f:
    f.write("// Generated by scripts/make-title-font.py: Inter SemiBold %d px\n" % size)
    f.write("// (SIL Open Font License, files/usr/share/fonts/inter). Do not edit.\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write("#define TITLEFONT_PX %d\n#define TITLEFONT_ASCENT %d\n#define TITLEFONT_DESCENT %d\n\n" % (size, ascent, descent))
    f.write("// code point, left and top offsets from the pen on the baseline,\n// width, height, advance (1/64 px), offset of the coverage bytes\n")
    f.write("typedef struct { uint16_t cp; int8_t dx, dy; uint8_t w, h; uint16_t adv; uint32_t off; } titlefont_glyph_t;\n\n")
    f.write("static const titlefont_glyph_t titlefont_glyphs[%d] = {\n" % len(glyphs))
    for g in glyphs:
        f.write("    {0x%04X, %d, %d, %d, %d, %d, %d},\n" % g)
    f.write("};\n\nstatic const uint8_t titlefont_data[%d] = {\n" % max(len(data), 1))
    for i in range(0, len(data), 24):
        f.write("    " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
    f.write("};\n")
print("%s: %d glyphs, %d bytes" % (out, len(glyphs), len(data)))
